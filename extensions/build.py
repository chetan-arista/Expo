"""
Build the ARACHNIX Companion browser extension (Chrome / Edge, Manifest V3).

    venv/Scripts/python.exe extensions/build.py            # regenerate data + icons, check, zip
    venv/Scripts/python.exe extensions/build.py --check    # only verify that extensions/chrome is up to date

What it does:
1. Data the extension reads (data only, no code), exported from ARACHNIX itself so the popup measures a page the
   way a crawl does:
   - chrome/data/widths.json  Google result pixel widths: the Roboto width tables of crawler/seo/text_metrics.py,
     plus the fallbacks that module uses (zero-width and wide characters) and Python's whitespace set.
   - chrome/data/rules.json   the text rules of crawler/seo/extract.py (block / hidden tags, invisible
     characters, robots names), the default thresholds of the SEO tabs, and the registrable-domain rules of
     crawler/url_utils.py.
2. Icons: chrome/icons/icon{16,32,48,128}.png resized with Pillow from web/static/brand/mark-512.png, and the
   brand mark (mark.svg) the popup header shows.
3. Checks: manifest.json is valid MV3 with the expected permissions, every file it names exists, no page loads
   a remote script or style, and `node --check` passes on every script (when Node is installed).
4. dist/arachnix-companion-<version>.zip: the contents of chrome/ (what "Load unpacked" or the Web Store takes),
   with fixed timestamps so the same sources give the same zip.
"""
import argparse
import io
import json
import os
import re
import shutil
import subprocess
import sys
import unicodedata
import zipfile
from typing import Dict, List, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CHROME = os.path.join(HERE, "chrome")
DIST = os.path.join(HERE, "dist")
BRAND = os.path.join(REPO, "web", "static", "brand")
ICON_SIZES = (16, 32, 48, 128)
ZIP_TIME = (2026, 1, 1, 0, 0, 0)          # fixed entry time: the same sources give a byte-identical zip
# Files the extension may ship (anything else in chrome/ is refused, so nothing stray ends up in the zip)
ALLOWED_EXT = {".json", ".js", ".html", ".css", ".png", ".svg"}
EXPECTED_PERMISSIONS = ["activeTab", "storage", "scripting"]
EXPECTED_OPTIONAL = ["cookies"]
EXPECTED_OPTIONAL_HOSTS = ["https://*/*", "http://*/*"]

sys.path.insert(0, REPO)


def _ranges(test) -> List[List[int]]:
    """[[first, last], ...] code point ranges (surrogates left out) where test(char) is true."""
    out: List[List[int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or not test(chr(cp)):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def widths_data() -> Dict:
    """Everything crawler.seo.text_metrics.pixel_width uses, as data."""
    from crawler.seo import text_metrics as tm
    kinds = {}
    for kind, runs in (("title", tm._TITLE_RUNS), ("description", tm._DESCRIPTION_RUNS)):
        table, fallback, em = tm._KINDS[kind]
        kinds[kind] = {"em": em, "fallback": fallback, "runs": [[start, widths] for start, widths in runs]}
    # The fallbacks of _char_width for a character the tables lack, in its order: zero first, then wide.
    zero = _ranges(lambda c: bool(unicodedata.combining(c)) or unicodedata.category(c) == "Cf")
    wide = _ranges(lambda c: not (unicodedata.combining(c) or unicodedata.category(c) == "Cf")
                   and unicodedata.east_asian_width(c) in ("W", "F"))
    return {
        "about": "Google result pixel widths as ARACHNIX measures them (crawler/seo/text_metrics.py): hinted Roboto "
                 "Regular advance widths, titles at 20px and descriptions at 14px. Each run is [first code point, "
                 "widths], one character per code point, width = code of the character - 48. Generated by "
                 "extensions/build.py; do not edit.",
        "unicode": unicodedata.unidata_version,
        "title": kinds["title"],
        "description": kinds["description"],
        "zero": zero,
        "wide": wide,
        "space": [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and chr(cp).isspace()],
    }


def rules_data() -> Dict:
    """The text rules, thresholds and registrable-domain rules the popup shares with a crawl."""
    from crawler import url_utils as uu
    from crawler.seo import extract as ex
    from crawler.seo.tabs import content, h1, meta_description as md, page_titles as pt
    invisible = _ranges(lambda c: bool(ex._INVISIBLE.fullmatch(c)))
    return {
        "about": "Rules ARACHNIX's crawl uses (crawler/seo/extract.py, the SEO tabs' default thresholds and "
                 "crawler/url_utils.py registrable_domain). Generated by extensions/build.py; do not edit.",
        "text": {
            "blockTags": sorted(ex.TEXT_BLOCK_TAGS),
            "hiddenTextTags": sorted(ex.HIDDEN_TEXT_TAGS),
            "contentExcludedTags": sorted(ex.CONTENT_EXCLUDED_TAGS),
            "robotsMetaNames": sorted(ex.ROBOTS_META_NAMES),
            "invisible": invisible,
            "directiveTokens": list(ex.DIRECTIVE_TOKENS),
            "valueDirectives": sorted(ex._VALUE_DIRECTIVES),
            "robotPrefixes": list(ex._ROBOT_PREFIXES),
        },
        "thresholds": {
            "titleMaxChars": pt.TITLE_MAX_CHARS, "titleMinChars": pt.TITLE_MIN_CHARS,
            "titleMaxPx": pt.TITLE_MAX_PX, "titleMinPx": pt.TITLE_MIN_PX,
            "descMaxChars": md.DESCRIPTION_MAX_CHARS, "descMinChars": md.DESCRIPTION_MIN_CHARS,
            "descMaxPx": md.DESCRIPTION_MAX_PX, "descMinPx": md.DESCRIPTION_MIN_PX,
            "h1MaxChars": h1.HEADING_MAX_CHARS, "lowContentWords": content.LOW_CONTENT_WORDS,
            "stored": pt.STORED,
        },
        "domains": {
            "ccSecondLevel": sorted(uu._CC_SECOND_LEVEL),
            "ccRegion2": sorted(uu._CC_REGION_2),
            "jpRegions": sorted(uu._JP_REGIONS),
            "platformSuffixes": sorted(uu._PLATFORM_SUFFIXES),
            "hostIsSite": sorted(uu._HOST_IS_SITE),
        },
    }


def _json_bytes(data: Dict) -> bytes:
    return (json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")


def icon_bytes() -> Dict[str, bytes]:
    """{relative path: PNG / SVG bytes} of the extension icons, made from the ARACHNIX brand mark."""
    from PIL import Image
    out: Dict[str, bytes] = {}
    with Image.open(os.path.join(BRAND, "mark-512.png")) as src:
        src = src.convert("RGBA")
        for size in ICON_SIZES:
            buf = io.BytesIO()
            src.resize((size, size), Image.LANCZOS).save(buf, format="PNG", optimize=True)
            out[f"icons/icon{size}.png"] = buf.getvalue()
    with open(os.path.join(BRAND, "mark.svg"), "rb") as f:
        out["icons/mark.svg"] = f.read()
    return out


def generated() -> Dict[str, bytes]:
    """Every generated file: {path relative to chrome/: bytes}."""
    files = {"data/widths.json": _json_bytes(widths_data()), "data/rules.json": _json_bytes(rules_data())}
    files.update(icon_bytes())
    return files


def _read(rel: str) -> bytes:
    try:
        with open(os.path.join(CHROME, rel), "rb") as f:
            return f.read()
    except OSError:
        return b""


def _png_pixels(data: bytes) -> bytes:
    """Decoded pixels of a PNG (Pillow's encoder may differ between versions; the picture is what counts)."""
    from PIL import Image
    try:
        with Image.open(io.BytesIO(data)) as im:
            return im.convert("RGBA").tobytes() + repr(im.size).encode()
    except Exception:
        return b""


def stale_files(files: Dict[str, bytes]) -> List[str]:
    out = []
    for rel, data in files.items():
        have = _read(rel)
        same = _png_pixels(have) == _png_pixels(data) if rel.endswith(".png") else have == data
        if not same:
            out.append(rel)
    return out


def write_generated(files: Dict[str, bytes]) -> List[str]:
    written = []
    for rel in stale_files(files):
        path = os.path.join(CHROME, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(files[rel])
        written.append(rel)
    return written


def package_files() -> List[str]:
    """Every file under chrome/, relative, sorted (forward slashes)."""
    out = []
    for root, dirs, names in os.walk(CHROME):
        dirs.sort()
        for n in sorted(names):
            out.append(os.path.relpath(os.path.join(root, n), CHROME).replace(os.sep, "/"))
    return sorted(out)


_REMOTE_REF = re.compile(r"""<(?:script|link|img|iframe)\b[^>]*\b(?:src|href)\s*=\s*["']?\s*(?:https?:)?//""", re.I)
_REMOTE_IMPORT = re.compile(r"""\bimport\s*(?:\(|[^;'"]*from\s*)\s*["'](?:https?:)?//|importScripts\s*\(|\beval\s*\(|new\s+Function\s*\(""")


def check_package() -> Tuple[List[str], Dict]:
    """(problems, manifest). Validates the manifest and the files without changing anything."""
    problems: List[str] = []
    try:
        with open(os.path.join(CHROME, "manifest.json"), encoding="utf-8") as f:
            manifest = json.load(f)
    except (OSError, ValueError) as e:
        return [f"manifest.json cannot be read: {e}"], {}
    if manifest.get("manifest_version") != 3:
        problems.append("manifest_version must be 3")
    if manifest.get("name") != "ARACHNIX Companion":
        problems.append('name must be "ARACHNIX Companion"')
    if not re.fullmatch(r"\d+(\.\d+){0,3}", str(manifest.get("version") or "")):
        problems.append("version must be 1 to 4 dot-separated numbers")
    if sorted(manifest.get("permissions") or []) != sorted(EXPECTED_PERMISSIONS):
        problems.append(f"permissions must be exactly {EXPECTED_PERMISSIONS}")
    if sorted(manifest.get("optional_permissions") or []) != sorted(EXPECTED_OPTIONAL):
        problems.append(f"optional_permissions must be exactly {EXPECTED_OPTIONAL}")
    if sorted(manifest.get("optional_host_permissions") or []) != sorted(EXPECTED_OPTIONAL_HOSTS):
        problems.append(f"optional_host_permissions must be exactly {EXPECTED_OPTIONAL_HOSTS}")
    if manifest.get("host_permissions"):
        problems.append("no host_permissions at install: hosts are asked for when needed")
    csp = ((manifest.get("content_security_policy") or {}).get("extension_pages") or "")
    if "script-src 'self'" not in csp or "object-src 'none'" not in csp or "unsafe" in csp:
        problems.append("content_security_policy.extension_pages must keep script-src 'self' and object-src 'none'")
    named = [manifest.get("background", {}).get("service_worker"), manifest.get("action", {}).get("default_popup"),
             manifest.get("options_ui", {}).get("page")]
    named += list((manifest.get("icons") or {}).values()) + list((manifest.get("action", {}).get("default_icon") or {}).values())
    for rel in named:
        if not rel or not os.path.isfile(os.path.join(CHROME, rel)):
            problems.append(f"the manifest names a missing file: {rel}")
    for rel in package_files():
        ext = os.path.splitext(rel)[1].lower()
        if ext not in ALLOWED_EXT:
            problems.append(f"unexpected file in chrome/: {rel}")
            continue
        if ext in (".html", ".js", ".css"):
            text = _read(rel).decode("utf-8", errors="replace")
            if ext == ".html" and (_REMOTE_REF.search(text) or re.search(r"<script(?![^>]*\bsrc=)[^>]*>", text, re.I)):
                problems.append(f"{rel}: a remote reference or an inline script (only local files may load)")
            if ext == ".js" and _REMOTE_IMPORT.search(text):
                problems.append(f"{rel}: remote import, importScripts or eval-like code")
            if ext == ".css" and re.search(r"@import|url\(\s*['\"]?(?:https?:)?//", text, re.I):
                problems.append(f"{rel}: the stylesheet loads something remote")
    return problems, manifest


def node_check() -> Tuple[List[str], bool]:
    """`node --check` on every script; (problems, ran)."""
    node = shutil.which("node")
    if not node:
        return [], False
    problems = []
    for rel in package_files():
        if rel.endswith(".js"):
            r = subprocess.run([node, "--check", os.path.join(CHROME, rel)], capture_output=True, text=True)
            if r.returncode:
                problems.append(f"node --check {rel}: {(r.stderr or r.stdout).strip().splitlines()[-1:]}")
    return problems, True


def build_zip(version: str) -> str:
    """dist/arachnix-companion-<version>.zip of chrome/ (deterministic). Returns its path."""
    os.makedirs(DIST, exist_ok=True)
    path = os.path.join(DIST, f"arachnix-companion-{version}.zip")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for rel in package_files():
            info = zipfile.ZipInfo(rel, date_time=ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, _read(rel))
    with open(path, "wb") as f:
        f.write(buf.getvalue())
    return path


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build the ARACHNIX Companion browser extension.")
    ap.add_argument("--check", action="store_true", help="only verify; change nothing (exit 1 when out of date)")
    ap.add_argument("--no-zip", action="store_true", help="regenerate and check, but do not write the zip")
    args = ap.parse_args(argv)

    files = generated()
    if args.check:
        stale = stale_files(files)
        for rel in stale:
            print(f"out of date: chrome/{rel} (run extensions/build.py)")
    else:
        stale = []
        for rel in write_generated(files):
            print(f"wrote chrome/{rel}")
    problems, manifest = check_package()
    node_problems, node_ran = node_check()
    problems += node_problems
    for p in problems:
        print(f"problem: {p}")
    if not node_ran:
        print("note: Node.js was not found, so the scripts were not syntax-checked")
    if problems or stale:
        return 1
    version = str(manifest.get("version"))
    if not args.check and not args.no_zip:
        path = build_zip(version)
        print(f"zip: {os.path.relpath(path, REPO)} ({os.path.getsize(path):,} bytes, {len(package_files())} files)")
    print(f"ARACHNIX Companion {version}: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
